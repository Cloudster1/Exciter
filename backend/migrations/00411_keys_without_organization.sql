-- +goose Up
-- An installation holds one organization (#82), so a key that was unique in it is unique in the installation, and
-- a foreign key that named it said only that the row existed (#106). Every key, foreign key and index is made
-- again without org_id under its name, or its name without the word org; the keys of the provider's and the
-- Armature connection's one row and the foreign keys to the organization go with the column (#108). This file is
-- written from the catalog at 00410.

-- A database written to by hand could hold rows that would share a new key; the upgrade names them instead of
-- failing half way.
-- +goose StatementBegin
DO $$
DECLARE
    clashes text[] := '{}';
    n bigint;
BEGIN
    SELECT count(*) INTO n FROM (SELECT 1 FROM armature_issue_link GROUP BY requirement_id, issue_key, relation HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in armature_issue_link (requirement_id, issue_key, relation)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM armature_issue_link GROUP BY id HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in armature_issue_link (id)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM armature_remote_link GROUP BY requirement_id, issue_key HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in armature_remote_link (requirement_id, issue_key)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM armature_token GROUP BY user_id HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in armature_token (user_id)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM oidc_group_role GROUP BY id HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in oidc_group_role (id)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM org_join_request GROUP BY user_id HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in org_join_request (user_id)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM org_member GROUP BY user_id HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in org_member (user_id)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM project_key_alias GROUP BY key HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in project_key_alias (key)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM requirement_label GROUP BY requirement_id, name HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in requirement_label (requirement_id, name)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM requirement_old_key GROUP BY key HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in requirement_old_key (key)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM requirement_revision GROUP BY requirement_id, number HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in requirement_revision (requirement_id, number)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM user_theme GROUP BY user_id HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in user_theme (user_id)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM groups GROUP BY lower(name) HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in groups (lower(name))', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM groups WHERE (external_ref IS NOT NULL) GROUP BY external_ref HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in groups (external_ref) WHERE (external_ref IS NOT NULL)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM link_type WHERE (project_id IS NULL) GROUP BY key HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in link_type (key) WHERE (project_id IS NULL)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM link_type WHERE (project_id IS NULL) GROUP BY lower(name) HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in link_type (lower(name)) WHERE (project_id IS NULL)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM oidc_group_role GROUP BY group_ref HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in oidc_group_role (group_ref)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM project GROUP BY key HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in project (key)', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM saved_view GROUP BY project_id, owner_id, lower(name) HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in saved_view (project_id, owner_id, lower(name))', n); END IF;
    SELECT count(*) INTO n FROM (SELECT 1 FROM theme GROUP BY owner_id, lower(name) HAVING count(*) > 1) d;
    IF n > 0 THEN clashes := clashes || format('%s in theme (owner_id, lower(name))', n); END IF;
    IF cardinality(clashes) > 0 THEN
        RAISE EXCEPTION 'Keys that were unique in each organization are unique in the installation from this release, and this database has rows that would share one: %. Rename or delete all but one of each, then upgrade again.', array_to_string(clashes[1:10], ', ');
    END IF;
END $$;
